"""Writes preview/assets/deskModel.ts: the uncompressed preview model as a base64 module."""
import base64, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
src = os.path.join(root, "preview", "assets", "desk.glb")
out = os.path.join(root, "preview", "assets", "deskModel.ts")
data = base64.b64encode(open(src, "rb").read()).decode()
open(out, "w").write("// generated by scripts/inline_preview_model.py\nexport default '" + data + "';\n")
print("wrote", out, len(data) // 1024, "KB")
